import './globals.css';

import { GoogleTagManager } from '@next/third-parties/google';
import type { Metadata } from 'next';
import { Lora } from 'next/font/google';
import localFont from 'next/font/local';
import { draftMode } from 'next/headers';
import Script from 'next/script';
import { VisualEditing } from 'next-sanity';

import { FooterNavigation } from '@/components/Footer';
import { OffCanvasNavigation } from '@/components/OffCanvasNavigation';
import { AnnouncementTypes, fetchAnnouncements } from '@/lib/announcements';
import {
  fetchAndTransformFooterNavigation,
  FooterNavigationType,
} from '@/lib/footer-utils';
import {
  fetchAndTransformOffCanvasNavigation,
  OffCanvasNavigationType,
} from '@/lib/off-canvas-navigation-utils';
import { SITE_URL } from '@/lib/seo';
import { cn } from '@/lib/utils';

const lora = Lora({ subsets: ['latin'], variable: '--font-lora' });

const atica = localFont({
  src: '../fonts/atica/Atica-Regular.woff2',
  display: 'swap',
  variable: '--font-atica',
});

export const metadata: Metadata = {
  metadataBase: new URL(SITE_URL),
  title: 'Create Next App',
  description: 'Generated by create next app',
};

export default async function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  const header: OffCanvasNavigationType =
    await fetchAndTransformOffCanvasNavigation();

  const footer: FooterNavigationType =
    await fetchAndTransformFooterNavigation();

  const announcements: AnnouncementTypes = await fetchAnnouncements();

  return (
    <html lang='en'>
      <GoogleTagManager gtmId='GTM-KJBGBTKZ' />

      <body
        className={cn(
          'flex min-h-dvh flex-col font-default transition-colors duration-1000 *:antialiased',
          lora.variable,
          atica.variable
        )}
      >
        {draftMode().isEnabled && (
          <div>
            <a className='block bg-blue-300 p-4' href='/api/disable-draft'>
              Disable preview mode
            </a>
          </div>
        )}
        {/* <Header /> */}
        <OffCanvasNavigation
          columns={header.columns}
          announcements={announcements?.announcements}
        />
        <main className='flex-1'>{children}</main>
        {draftMode().isEnabled && <VisualEditing />}
        <FooterNavigation
          columns={footer.columns}
          address={footer.address}
          instagramUrl={footer.instagramUrl}
          legalText={footer.legalText}
          allpages={header.columns}
          furtherLinks={footer.furtherLinks}
          miscellaneousText={footer.miscellaneousText}
        />

        {/** Accessibe */}
        <Script
          id='accessibe'
          strategy='beforeInteractive'
          dangerouslySetInnerHTML={{
            __html: `
          (function(){
            var s = document.createElement('script');
            var h = document.querySelector('head') || document.body;
            s.src = 'https://acsbapp.com/apps/app/dist/js/app.js';
            s.async = true;
            s.onload = function(){
              acsbJS.init({
                statementLink : '',
                footerHtml : '',
                 hideMobile : false,
                 hideTrigger : false,
                 disableBgProcess : false,
                 language : 'en',
                 position : 'right',
                 leadColor : '#000000',
                 triggerColor : '#000000',
                 triggerRadius : '50%',
                 triggerPositionX : 'right',
                 triggerPositionY : 'bottom',
                 triggerIcon : 'people',
                 triggerSize : 'bottom',
                 triggerOffsetX : 20,
                 triggerOffsetY : 20,
                 mobile : {
                  triggerSize : 'small',
                  triggerPositionX : 'right',
                  triggerPositionY : 'bottom',
                  triggerOffsetX : 15,
                  triggerOffsetY : 15,
                  triggerRadius : '20'
                }
              });
            };
            h.appendChild(s); })();
            `,
          }}
        />
      </body>
    </html>
  );
}
